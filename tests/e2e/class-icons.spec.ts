import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('OJ icons are local display settings, isolated by exercise and excluded from grading', async ({ page }) => {
  let network = 0
  await page.route('https://api.iconify.design/**', async route => { network++; await route.abort() })
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  const node = page.getByRole('button', { name: '编辑类 Example' })
  await expect(node.locator('.class-icon-badge')).toHaveAttribute('data-icon', 'lucide:box')
  const original = await source.inputValue()
  await node.click()
  await page.getByLabel('类图标', { exact: true }).selectOption('umloom:surgery-room')
  await expect(node.locator('.class-icon-badge')).toHaveAttribute('data-icon', 'umloom:surgery-room')
  await expect(source).toHaveValue(original)
  await page.getByLabel('类名', { exact: true }).fill('Student')
  await page.getByRole('button', { name: '应用更改' }).click()
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByText('本关通过！')).toBeVisible()
  await expect(page.getByRole('button', { name: '编辑类 Student' }).locator('.class-icon-badge')).toHaveAttribute('data-icon', 'umloom:surgery-room')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '备份草稿' }).click()
  const backup = JSON.parse(await readFile((await (await downloadPromise).path())!, 'utf8'))
  expect(backup.icons.choices.Student).toEqual({ kind: 'umloom', id: 'surgery-room' })
  await page.reload()
  await expect(page.getByRole('button', { name: '编辑类 Student' }).locator('.class-icon-badge')).toHaveAttribute('data-icon', 'umloom:surgery-room')
  await page.getByLabel('选择教学关卡').selectOption('learn-attribute')
  await page.getByRole('button', { name: '隐藏类图标' }).click()
  await page.getByLabel('选择教学关卡').selectOption('learn-class')
  await expect(page.getByRole('button', { name: '隐藏类图标' })).toBeVisible()
  await expect(page.getByRole('button', { name: '编辑类 Student' }).locator('.class-icon-badge')).toHaveAttribute('data-icon', 'umloom:surgery-room')
  expect(network).toBe(0)
})

test('OJ can search Iconify only by explicit action and retains cached results offline', async ({ page }) => {
  let requests = 0
  await page.route('https://api.iconify.design/**', async route => {
    requests++
    const url = new URL(route.request().url())
    if (url.pathname === '/search') await route.fulfill({ json: { icons: ['tabler:plane'] } })
    else await route.fulfill({ json: { prefix: 'tabler', width: 24, height: 24, icons: { plane: { body: '<path d="M2 12h20" stroke="currentColor"/>' } } } })
  })
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  await page.getByRole('button', { name: '编辑类 Example' }).click()
  await page.getByText('搜索开源图标（需联网）').click()
  await expect(page.getByText(/关键词将发送到 Iconify/)).toBeVisible()
  expect(requests).toBe(0)
  await page.getByLabel('图标搜索关键词').fill('airplane')
  await page.getByRole('button', { name: '搜索图标' }).click()
  await page.getByRole('button', { name: '选择图标 plane' }).click()
  await expect(page.getByRole('button', { name: '编辑类 Example' }).locator('.class-icon-badge')).toHaveAttribute('data-icon', 'iconify:plane')
  expect(requests).toBe(2)
  await page.reload()
  await expect(page.getByRole('button', { name: '编辑类 Example' }).locator('.class-icon-badge')).toHaveAttribute('data-icon', 'iconify:plane')
  await page.getByLabel('选择教学关卡').selectOption('learn-attribute')
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await page.getByLabel('类图标', { exact: true }).selectOption('iconify:plane')
  await expect(page.getByRole('button', { name: '编辑类 Student' }).locator('.class-icon-badge')).toHaveAttribute('data-icon', 'iconify:plane')
  expect(requests).toBe(2)
})
