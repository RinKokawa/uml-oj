import { expect, test } from '@playwright/test'

test('OJ element picker supports keyboard and outside dismissal', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const trigger = page.getByRole('button', { name: '添加元素' })
  const picker = page.getByRole('group', { name: '可添加的元素' })
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await trigger.focus()
  await page.keyboard.press('Enter')
  await expect(picker).toBeVisible()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('button', { name: '添加类', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: '添加接口', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(picker).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.getByRole('heading', { name: '开始建模' }).click()
  await expect(picker).toBeHidden()
})

test('picker preserves pending edits and allows choosing a relation type', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  await page.getByRole('button', { name: '编辑类 Example' }).click()
  await page.getByLabel('类名', { exact: true }).fill('Draft')
  await page.getByRole('button', { name: '添加元素' }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '添加接口', exact: true }).click()
  await expect(page.getByLabel('类名', { exact: true })).toHaveValue('Draft')
  await expect(page.getByRole('button', { name: '编辑接口 Interface1' })).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveAttribute('readonly', '')
  await page.getByRole('button', { name: '撤销编辑' }).click()
  await page.getByRole('button', { name: '添加元素' }).click()
  await page.getByRole('button', { name: '添加接口', exact: true }).click()
  await expect(page.getByRole('button', { name: '编辑接口 Interface1' })).toBeVisible()
  await page.getByRole('button', { name: '添加关联' }).click()
  await page.getByRole('button', { name: '选为起点 Example' }).click()
  await page.getByRole('button', { name: '选为终点 Interface1' }).click()
  await expect(page.getByLabel('关联方向').locator('option')).toHaveText(['普通关联（无方向）', '普通关联（起点 → 终点）', '继承（起点 → 父类）', '实现（起点 → 接口）'])
})

test('mobile element picker remains within the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  await page.getByRole('button', { name: '画布模式' }).click()
  await page.getByRole('button', { name: '添加元素' }).click()
  const picker = page.getByRole('group', { name: '可添加的元素' })
  const box = (await picker.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(320)
  await page.getByRole('button', { name: '添加接口', exact: true }).click()
  await expect(page.getByLabel('接口名')).toHaveValue('Interface1')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
})
