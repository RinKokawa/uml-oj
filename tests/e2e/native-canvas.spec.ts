import { expect, test } from '@playwright/test'

test('edit a class on the local canvas, protect pending changes, judge and restore', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  await expect(page.locator('.statusbar')).toContainText('已同步')
  await page.getByRole('button', { name: '编辑类 Example' }).click()
  await page.getByLabel('类名', { exact: true }).fill('Student')
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await expect(source).toHaveAttribute('readonly', '')
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.locator('.error-report')).toContainText('未应用')
  await expect(source).toHaveValue(/class Example/)
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).toHaveValue(/class Student/)
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByText('本关通过！')).toBeVisible()
  await page.reload()
  await expect(source).toHaveValue(/class Student/)
  await expect(page.getByRole('button', { name: '编辑类 Student' })).toBeVisible()
  await expect(page.locator('iframe')).toHaveCount(0)
})

test('level four multiplicities can be edited directly and judged', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 4 关：读懂一对多' }).click()
  await page.getByRole('button', { name: '编辑关联 Classroom 到 Student' }).click()
  await page.getByLabel('Classroom端多重性（起点）').fill('1')
  await page.getByLabel('Student端多重性（终点）').fill('0..*')
  await page.getByRole('button', { name: '应用更改' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await expect(source).toHaveValue(/Classroom "1" -- "0\.\.\*" Student/)
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByText('本关通过！')).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '编辑关联 Classroom 到 Student' }).click()
  await expect(page.getByLabel('Classroom端多重性（起点）')).toHaveValue('1')
  await expect(page.getByLabel('Student端多重性（终点）')).toHaveValue('0..*')
})

test('unfinished source is not judged or allowed to overwrite the canvas', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await source.fill('@startuml\nclass Student\n@enduml')
  await expect(page.locator('.statusbar')).toContainText('已同步')
  await source.fill('@startuml\nenum Student\n@enduml')
  await expect(page.locator('.statusbar')).toContainText('未同步')
  await expect(page.getByRole('button', { name: '编辑类 Student' })).toBeVisible()
  await expect(page.getByRole('button', { name: '添加类' })).toBeDisabled()
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.locator('.error-report')).toBeVisible()
  await page.reload()
  await expect(source).toHaveValue(/enum Student/)
  await expect(page.getByRole('button', { name: '编辑类 Student' })).toBeVisible()
  await source.fill('@startuml\nclass Student\n@enduml')
  await expect(page.locator('.statusbar')).toContainText('已同步')
})

test('add classes and associations and prevent navigation with pending edits', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  await page.getByRole('button', { name: '添加类' }).click()
  await expect(page.getByRole('button', { name: '编辑类 Class1' })).toBeVisible()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  const before = await source.inputValue()
  const addRelation = page.getByRole('button', { name: '添加关联' })
  await addRelation.click()
  await page.getByRole('button', { name: '选为起点 Example' }).click()
  await expect(page.getByText('起点：Example。请选择终点（Esc 取消）')).toBeVisible()
  await expect(source).toHaveValue(before)
  await expect(page.locator('.canvas-edge')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(addRelation).toBeFocused()
  await expect(source).toHaveValue(before)
  await expect(page.locator('.canvas-edge')).toHaveCount(0)
  await addRelation.click()
  await page.getByRole('button', { name: '选为起点 Example' }).press('Enter')
  await page.getByRole('button', { name: '选为终点 Class1' }).press('Space')
  await expect(page.getByRole('button', { name: '编辑关联 Example 到 Class1' })).toBeVisible()
  await page.getByLabel('Example端多重性（起点）').fill('1')
  await page.getByRole('button', { name: '返回教学关卡' }).click()
  await expect(page.locator('.error-report')).toContainText('未应用')
  await expect(page.getByLabel('Example端多重性（起点）')).toHaveValue('1')
  await page.getByRole('button', { name: '应用更改' }).click()
  await page.getByRole('button', { name: '返回教学关卡' }).click()
  await expect(page.getByRole('heading', { name: '教学关卡', exact: true })).toBeVisible()
})

