import { expect, test } from '@playwright/test'
import { installDrawio } from './fixture'
test.beforeEach(async ({ page }) => installDrawio(page))

test('desktop uses a focused workbench with independently scrollable statement and results', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 720 })
  await page.goto('/')
  await page.getByRole('button', { name: '正式挑战', exact: true }).click()
  await page.getByRole('button', { name: '开始作答：图书借阅系统' }).click()
  const statement = page.locator('.problem-scroll')
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  const resultToggle = page.getByRole('button', { name: /评测结果.*当前答案未评测/ })
  await expect(resultToggle).toHaveAttribute('aria-expanded', 'false')
  expect(await page.evaluate(() => document.documentElement.scrollHeight)).toBeLessThanOrEqual(720)
  const before = await source.boundingBox()
  await statement.evaluate(el => { el.scrollTop = el.scrollHeight })
  expect(await statement.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByRole('button', { name: /评测结果.*未通过/ })).toHaveAttribute('aria-expanded', 'true')
  await expect(page.locator('.feedback-content .result-row')).toHaveCount(13)
  await expect(page.locator('.feedback-anchor')).toBeInViewport()
  await expect(source).toBeInViewport()
  expect((await source.boundingBox())!.height).toBeLessThan(before!.height)
  const results = page.locator('.feedback-content')
  await results.evaluate(el => { el.scrollTop = el.scrollHeight })
  expect(await results.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  expect(await page.evaluate(() => window.scrollY)).toBe(0)
  await page.getByRole('button', { name: /评测结果.*未通过/ }).click()
  await expect(page.locator('.feedback-content')).toBeHidden()
  await expect(source).toBeInViewport()
})

test('splitter adjusts statement width by keyboard and pointer without losing source', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const separator = page.getByRole('separator', { name: '调整题面宽度' })
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await source.click(); await expect(source).toBeEditable(); await source.fill('@startuml\nclass Example\n@enduml')
  await expect(separator).toHaveAttribute('aria-valuenow', '32')
  await separator.focus()
  await page.keyboard.press('ArrowRight')
  await expect(separator).toHaveAttribute('aria-valuenow', '34')
  const box = (await separator.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 - 100, box.y + box.height / 2, { steps: 5 })
  await page.mouse.up()
  expect(Number(await separator.getAttribute('aria-valuenow'))).toBeLessThan(34)
  await expect(source).toHaveValue('@startuml\nclass Example\n@enduml')
})

