import { expect, test, type Locator } from '@playwright/test'

const geometry = (element: Locator) => element.evaluate(el => {
  const { x, y, width, height } = el.getBoundingClientRect()
  return { x, y, width, height }
})

test('structured attribute editor completes lesson two and survives refresh while pending', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 2 关：给类添加属性' }).click()
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await page.getByRole('button', { name: '添加属性' }).click()
  await page.getByLabel('属性 1 名称').fill('name')
  await page.getByLabel('属性 1 类型').fill('String')
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await expect(source).toHaveAttribute('readonly', '')
  page.on('dialog', dialog => dialog.accept())
  await page.reload()
  await expect(page.getByLabel('属性 1 名称')).toHaveValue('name')
  await expect(page.getByLabel('属性 1 类型')).toHaveValue('String')
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.locator('.error-report')).toContainText('未应用')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).toHaveValue(/- name: String/)
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByText('本关通过！')).toBeVisible()
})

