test('association labels follow the selected classes and failed serialization stays editable', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 4 关：读懂一对多' }).click()
  await page.getByRole('button', { name: '编辑关联 Classroom 到 Student' }).click()
  await expect(page.getByLabel('Classroom端多重性（起点）')).toBeVisible()
  await expect(page.getByLabel('Student端多重性（终点）')).toBeVisible()
  await expect(page.getByText('每端的数量表示', { exact: false })).toBeVisible()
  await page.getByLabel('起点类').selectOption('Student')
  await expect(page.getByLabel('Student端多重性（起点）')).toBeVisible()
  await page.getByLabel('起点类').selectOption('Classroom')
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  const before = await source.inputValue()
  await page.getByLabel('关系名称').fill('bad"')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(page.locator('.inspector-error')).toContainText('无法同步源码')
  await expect(source).toHaveValue(before)
  await expect(page.getByLabel('关系名称')).toBeEditable()
  await page.getByRole('button', { name: '撤销编辑' }).click()
  await expect(page.locator('.statusbar')).toContainText('已同步')
  await page.getByLabel('关系名称').fill('bad"')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(page.locator('.inspector-error')).toContainText('无法同步源码')
  await page.getByLabel('关系名称').fill('enrolls')
  await page.getByLabel('Classroom端多重性（起点）').fill('1')
  await page.getByLabel('Student端多重性（终点）').fill('0..*')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).toHaveValue(/Classroom "1" -- "0\.\.\*" Student : enrolls/)
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByText('本关通过！')).toBeVisible()
})

test('opening and closing inspector does not move canvas elements', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 4 关：读懂一对多' }).click()
  const canvas = page.locator('.canvas-scroll')
  const body = page.getByRole('button', { name: '编辑类 Classroom' }).locator('.node-body')
  const edge = page.locator('.canvas-edge .edge-line').first()
  const before = await Promise.all([geometry(canvas), geometry(body), geometry(edge)])
  await page.getByRole('button', { name: '编辑类 Classroom' }).click()
  const panel = page.getByRole('complementary', { name: '类属性面板' })
  await expect.poll(() => panel.evaluate(el => getComputedStyle(el).transform)).toBe('none')
  const after = await Promise.all([geometry(canvas), geometry(body), geometry(edge)])
  expect(after).toEqual(before)
  await page.getByRole('button', { name: '关闭编辑面板' }).click()
  await expect(panel).toHaveCount(0)
  expect(await Promise.all([geometry(canvas), geometry(body), geometry(edge)])).toEqual(before)
})

test('an earlier unstructured pending draft is restored without losing members', async ({ page }) => {
  await page.addInitScript(() => {
    const model = { classes: [{ name: 'Student', abstract: false, attributes: [], methods: [] }], relations: [] }
    const form = { name: 'Student', attributes: '- name: String\n', methods: '+ study(): void', source: '', target: '', sourceMultiplicity: '', targetMultiplicity: '', label: '', type: 'ClassBidirectional' }
    localStorage.setItem('uml-oj-native-pending-v1:learn-attribute', JSON.stringify({ modelKey: JSON.stringify(model), selection: { kind: 'class', index: 0 }, form }))
  })
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 2 关：给类添加属性' }).click()
  await expect(page.getByLabel('属性 1 名称')).toHaveValue('name')
  await expect(page.getByLabel('方法 1 名称')).toHaveValue('study')
  await page.getByRole('button', { name: '应用更改' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await expect(source).toHaveValue(/- name: String/)
  await expect(source).toHaveValue(/\+ study\(\): void/)
})
