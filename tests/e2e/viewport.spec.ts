import { expect, test } from '@playwright/test'

test('OJ canvas navigation preserves pending edits, source and grading', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const svg = page.getByLabel('类图画布')
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  const original = await source.inputValue()
  await page.getByRole('button', { name: '编辑类 Example' }).click()
  await page.getByLabel('类名', { exact: true }).fill('Student')
  await page.getByRole('button', { name: '放大画布' }).click()
  await expect(page.getByLabel('画布缩放比例')).toHaveText('120%')
  await expect(page.getByLabel('类名', { exact: true })).toHaveValue('Student')
  await expect(source).toHaveValue(original)
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.locator('.error-report')).toContainText('未应用')
  await page.getByRole('button', { name: '应用更改' }).click()
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByText('本关通过！')).toBeVisible()
  await page.getByRole('button', { name: '关闭编辑面板' }).click()
  const before = await svg.getAttribute('viewBox')
  const box = (await svg.boundingBox())!
  const x = box.x + box.width * .8, y = box.y + box.height * .65
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x - 30, y - 30, { steps: 4 })
  await page.mouse.up()
  await expect(svg).not.toHaveAttribute('viewBox', before!)
  await expect(source).toHaveValue(/class Student/)
  await page.getByRole('button', { name: '适应内容' }).click()
  await expect(page.getByRole('button', { name: '编辑类 Student' })).toBeInViewport()
  await page.getByRole('button', { name: '重置视图' }).click()
  expect((await svg.getAttribute('viewBox'))!.split(' ').slice(0, 2)).toEqual(['0', '0'])
})

