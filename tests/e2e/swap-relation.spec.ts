import { expect, test } from '@playwright/test'

test('swapping an association carries its multiplicities and still passes the lesson', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 4 关：读懂一对多' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  const initial = await source.inputValue()
  await page.getByRole('button', { name: '编辑关联 Classroom 到 Student' }).click()
  await page.getByLabel('Classroom端多重性（起点）').fill('1')
  await page.getByLabel('Student端多重性（终点）').fill('0..*')
  await page.getByRole('button', { name: '交换起点和终点' }).click()
  await expect(page.getByLabel('起点类')).toHaveValue('Student')
  await expect(page.getByLabel('Student端多重性（起点）')).toHaveValue('0..*')
  await expect(page.getByLabel('终点类')).toHaveValue('Classroom')
  await expect(page.getByLabel('Classroom端多重性（终点）')).toHaveValue('1')
  await expect(source).toHaveValue(initial)
  await expect(source).toHaveAttribute('readonly', '')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).toHaveValue(/Student "0\.\.\*" -- "1" Classroom/)
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByText('本关通过！')).toBeVisible()
  await page.getByLabel('源码格式').selectOption('mermaid')
  await expect(page.getByRole('textbox', { name: 'Mermaid source' })).toHaveValue(/Student "0\.\.\*" -- "1" Classroom/)
})

test('swapping inheritance reverses child and parent without changing the relation type', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 4 关：读懂一对多' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await source.fill('@startuml\nclass Child\nclass Parent\nChild --|> Parent\n@enduml')
  await page.getByRole('button', { name: '编辑关联 Child 到 Parent' }).click()
  await expect(page.getByLabel('关联方向')).toHaveValue('ClassInheritance')
  await page.getByRole('button', { name: '交换起点和终点' }).click()
  await expect(page.getByLabel('起点类')).toHaveValue('Parent')
  await expect(page.getByLabel('终点类')).toHaveValue('Child')
  await expect(page.getByLabel('关联方向')).toHaveValue('ClassInheritance')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).toHaveValue(/Parent --\|> Child/)
})
