import { expect, test } from '@playwright/test'

test('lesson 5 requires an interface, not a class, and canvas can complete it', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 5 关：认识接口' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await source.fill('@startuml\nclass Printable\n@enduml')
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.locator('.result-row').filter({ hasText: 'Printable 接口' })).toContainText('FAIL')
  await source.fill('@startuml\ninterface Example\n@enduml')
  await expect(page.getByRole('button', { name: '编辑接口 Example' })).toBeVisible()
  await page.getByRole('button', { name: '编辑接口 Example' }).click()
  await page.getByLabel('接口名').fill('Printable')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).toHaveValue(/interface Printable/)
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByText('本关通过！')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '编辑接口 Printable' })).toContainText('<<interface>>')
})

test('lesson 6 checks methods, not attributes, and supports structured parameter editing', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 6 关：接口的方法' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await source.fill('@startuml\ninterface Payable {\n+ pay: Boolean\n}\n@enduml')
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.locator('.result-row').filter({ hasText: '包含方法 pay' })).toContainText('FAIL')
  await source.fill('@startuml\ninterface Payable\n@enduml')
  await expect(page.locator('.statusbar')).toContainText('已同步')
  await expect(page.getByRole('button', { name: '编辑接口 Payable' })).toBeVisible()
  await page.getByRole('button', { name: '编辑接口 Payable' }).click()
  await page.getByRole('button', { name: '添加方法' }).click()
  await page.getByLabel('方法 1 名称').fill('pay')
  await page.getByLabel('方法 1 返回类型').fill('Boolean')
  await page.getByRole('button', { name: '为方法 1 添加参数' }).click()
  await page.getByLabel('方法 1 参数 1 名称').fill('amount')
  await page.getByLabel('方法 1 参数 1 类型').fill('Money')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).toHaveValue(/\+ pay\(amount: Money\): Boolean/)
  await page.getByLabel('源码格式').selectOption('mermaid')
  await expect(page.getByRole('textbox', { name: 'Mermaid source' })).toHaveValue(/<<interface>>[\s\S]*pay\(amount: Money\) Boolean/)
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByText('本关通过！')).toBeVisible()
})

test('lesson 7 creates two interfaces and preserves them across reload', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 7 关：多个接口' }).click()
  await page.getByRole('button', { name: '编辑接口 Searchable' }).click()
  await page.getByRole('button', { name: '添加方法' }).click()
  await page.getByLabel('方法 1 名称').fill('search')
  await page.getByRole('button', { name: '应用更改' }).click()
  await page.getByRole('button', { name: '添加元素' }).click()
  await page.getByRole('button', { name: '添加接口' }).click()
  await page.getByLabel('接口名').fill('Exportable')
  await page.getByRole('button', { name: '添加方法' }).click()
  await page.getByLabel('方法 1 名称').fill('export')
  await page.getByRole('button', { name: '应用更改' }).click()
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.getByText('本关通过！')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '编辑接口 Searchable' })).toBeVisible()
  await expect(page.getByRole('button', { name: '编辑接口 Exportable' })).toBeVisible()
})
