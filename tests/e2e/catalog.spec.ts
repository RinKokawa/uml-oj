import { expect, test } from '@playwright/test'
import { installDrawio } from './fixture'
test.beforeEach(async ({ page }) => installDrawio(page))

test('catalogs and workspaces are separate, and drafts and progress survive reload', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '教学关卡', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: '教学关卡列表' }).locator('article')).toHaveCount(7)
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toBeHidden()
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await source.click(); await expect(source).toBeEditable(); await source.fill('@startuml\nclass Student\n@enduml')
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.locator('.verdict')).toContainText('本关通过')
  await page.getByRole('button', { name: '返回教学关卡' }).click()
  await expect(page.getByRole('region', { name: '教学关卡列表' }).locator('article').first()).toContainText('已完成')
  await page.getByRole('button', { name: '正式挑战', exact: true }).click()
  await expect(page.getByRole('region', { name: '正式题目列表' }).locator('article')).toHaveCount(5)
  await page.getByRole('button', { name: '开始作答：项目管理系统' }).click()
  await source.click(); await expect(source).toBeEditable(); await source.fill('@startuml\nclass Developer {\n - name: String\n}\n@enduml')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('uml-oj-native-drafts-v1') || '{}')?.drafts?.['project-management']?.source)).toContain('Developer')
  await page.reload()
  await expect(source).toHaveValue(/class Developer/)
  await page.getByRole('button', { name: '教学关卡', exact: true }).click()
  await expect(page.getByRole('region', { name: '教学关卡列表' }).locator('article').first()).toContainText('已完成')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  await expect(source).toHaveValue('@startuml\nclass Student\n@enduml')
})

test('reports follow the evaluated draft across reload and question switches', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '正式挑战', exact: true }).click()
  await page.getByRole('button', { name: '开始作答：项目管理系统' }).click()
  const submit = page.getByRole('button', { name: '提交评测' })
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  const answer = '@startuml\nclass Developer {\nname\nemployeeId\n}\nclass Project {\nname\nstartDate\n}\nDeveloper "0..*" -- "0..*" Project\n@enduml'
  await source.fill(answer.replaceAll('0..*', '1'))
  await submit.click()
  await expect(page.locator('.score strong')).toHaveText('7/8')
  await page.reload()
  await page.getByRole('button', { name: /评测结果 未通过.*7\/8/ }).click()
  await expect(page.getByText('请在同一条普通关联的 Developer 端填写 0..*，Project 端填写 0..*。')).toBeVisible()
  await source.fill(answer)
  await submit.click()
  await expect(page.locator('.score strong')).toHaveText('8/8')
  await page.reload()
  await expect(page.getByRole('button', { name: '评测结果 通过 · 8/8', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: '源码格式' }).selectOption('mermaid')
  await expect(page.getByRole('button', { name: '评测结果 通过 · 8/8', exact: true })).toBeVisible()
  const question = page.getByRole('combobox', { name: '选择正式关卡' })
  await question.selectOption({ label: '2. 图书借阅系统' })
  await expect(page.getByRole('button', { name: /评测结果 当前答案未评测/ })).toBeVisible()
  await question.selectOption({ label: '1. 项目管理系统（已完成）' })
  await expect(page.getByRole('button', { name: '评测结果 通过 · 8/8', exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: 'Mermaid source' }).fill('classDiagram\nclass Developer')
  await page.reload()
  await expect(page.getByRole('button', { name: /评测结果 当前答案未评测/ })).toBeVisible()
})

test('catalog search, completion filters and empty reset work at phone width', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '正式挑战', exact: true }).click()
  const list = page.getByRole('region', { name: '正式题目列表' })
  const search = list.getByRole('searchbox', { name: '搜索题目' })
  const rows = list.getByRole('article')
  await expect(rows).toHaveCount(5)
  await search.fill('  终稿  ')
  await expect(rows).toHaveCount(1)
  await expect(rows.locator('.catalog-number')).toHaveText('05')
  await list.getByRole('button', { name: '已完成', exact: true }).click()
  await expect(rows).toHaveCount(0)
  await expect(list.getByText('没有符合条件的题目。')).toBeVisible()
  await list.getByRole('button', { name: '清除搜索和筛选' }).click()
  await expect(search).toHaveValue('')
  await expect(list.getByRole('button', { name: '全部', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(rows).toHaveCount(5)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await search.fill('雷达')
  await page.getByRole('button', { name: '教学关卡', exact: true }).click()
  await expect(page.getByRole('searchbox', { name: '搜索题目' })).toHaveValue('')
  await expect(page.getByRole('region', { name: '教学关卡列表' }).getByRole('article')).toHaveCount(7)
})
