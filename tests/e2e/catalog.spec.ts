import { expect, test } from '@playwright/test'

test('catalogs and workspaces are separate, and drafts and progress survive reload', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '教学关卡', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: '教学关卡列表' }).locator('article')).toHaveCount(4)
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toBeHidden()
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await source.fill('@startuml\nclass Student\n@enduml')
  await page.getByRole('button', { name: '提交评测' }).click()
  await expect(page.locator('.verdict')).toContainText('本关通过')
  await page.getByRole('button', { name: '返回教学关卡' }).click()
  await expect(page.getByRole('region', { name: '教学关卡列表' }).locator('article').first()).toContainText('已完成')
  await page.getByRole('button', { name: '正式挑战', exact: true }).click()
  await expect(page.getByRole('region', { name: '正式题目列表' }).locator('article')).toHaveCount(2)
  await page.getByRole('button', { name: '开始作答：项目管理系统' }).click()
  await source.fill('@startuml\nclass Developer {\n - name: String\n}\n@enduml')
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('uml-oj-drafts-v1') || '{}')?.drafts?.['project-management']?.source)).toContain('Developer')
  await page.reload()
  await expect(source).toHaveValue(/class Developer/)
  await page.getByRole('button', { name: '教学关卡', exact: true }).click()
  await expect(page.getByRole('region', { name: '教学关卡列表' }).locator('article').first()).toContainText('已完成')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  await expect(source).toHaveValue('@startuml\nclass Student\n@enduml')
})

test('canvas drafts survive reload and remain convertible', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  await page.getByRole('textbox', { name: 'PlantUML source' }).fill('@startuml\nclass Student\n@enduml')
  await page.getByRole('button', { name: '切换到可视化绘图' }).click()
  await page.locator('.react-flow__node').filter({ hasText: 'Student' }).dblclick()
  await page.getByPlaceholder('Name', { exact: true }).first().fill('Learner')
  await expect.poll(() => page.evaluate(() => JSON.stringify(JSON.parse(localStorage.getItem('uml-oj-drafts-v1') || '{}')?.drafts?.['learn-class']?.model))).toContain('Learner')
  await page.reload()
  await expect(page.locator('.react-flow__node').filter({ hasText: 'Learner' })).toBeVisible()
  await page.getByRole('button', { name: 'PlantUML 源码模式' }).click()
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveValue(/class Learner/)
})
