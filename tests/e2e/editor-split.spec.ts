import { expect, test } from '@playwright/test'

test('resize canvas and source with keyboard and pointer, preserve source and preference', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const splitter = page.getByRole('separator', { name: '调整画布和源码宽度' })
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  const visual = page.locator('.visual-pane')
  const text = '@startuml\nclass Custom\n@enduml'
  await source.fill(text)
  await expect(page.locator('.statusbar')).toContainText('已同步')
  await expect(page.getByRole('button', { name: '编辑类 Custom' })).toBeVisible()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('uml-oj-native-drafts-v1'))).toContain('Custom')
  const sourceBefore = (await source.boundingBox())!.width
  const canvasBefore = (await visual.boundingBox())!.width
  await splitter.focus()
  await page.keyboard.press('ArrowRight')
  await expect(splitter).toHaveAttribute('aria-valuenow', '52')
  expect((await source.boundingBox())!.width).toBeLessThan(sourceBefore)
  expect((await visual.boundingBox())!.width).toBeGreaterThan(canvasBefore)
  const box = (await splitter.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 140, box.y + box.height / 2, { steps: 6 })
  await page.mouse.up()
  const resized = Number(await splitter.getAttribute('aria-valuenow'))
  expect(resized).toBeGreaterThan(52)
  expect((await source.boundingBox())!.width).toBeLessThan(sourceBefore - 100)
  await expect(source).toHaveValue(text)
  await expect(page.getByRole('button', { name: '编辑类 Custom' })).toBeVisible()
  await page.reload()
  await expect(splitter).toHaveAttribute('aria-valuenow', String(resized))
  await expect(source).toHaveValue(text)
  await splitter.focus()
  await page.keyboard.press('End')
  const max = await splitter.getAttribute('aria-valuemax')
  await expect(splitter).toHaveAttribute('aria-valuenow', max!)
  expect((await source.boundingBox())!.width).toBeGreaterThanOrEqual(159)
  expect((await visual.boundingBox())!.width).toBeGreaterThanOrEqual(199)
  await expect(page.getByLabel('源码格式')).toBeVisible()
  await page.keyboard.press('Home')
  await expect(splitter).toHaveAttribute('aria-valuenow', (await splitter.getAttribute('aria-valuemin'))!)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  // Wide windows can reduce source below 20%, while retaining a usable minimum.
  await page.setViewportSize({ width: 2200, height: 900 })
  await expect.poll(async () => Number(await splitter.getAttribute('aria-valuemax'))).toBeGreaterThan(80)
  await splitter.focus()
  await page.keyboard.press('End')
  const wideRatio = await splitter.getAttribute('aria-valuenow')
  expect((await source.boundingBox())!.width).toBeGreaterThanOrEqual(159)
  expect((await source.boundingBox())!.width).toBeLessThan(200)
  await page.reload()
  await expect(splitter).toHaveAttribute('aria-valuenow', wideRatio!)
  await expect(source).toHaveValue(text)
})

test('resizing keeps pending canvas edits and mobile mode safe', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  await page.getByRole('button', { name: '编辑类 Example' }).click()
  await page.getByLabel('类名', { exact: true }).fill('Student')
  const splitter = page.getByRole('separator', { name: '调整画布和源码宽度' })
  await splitter.focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByLabel('类名', { exact: true })).toHaveValue('Student')
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveAttribute('readonly', '')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(splitter).toHaveCount(0)
  await expect(page.getByRole('button', { name: '画布模式' })).toBeVisible()
  await page.getByRole('button', { name: '画布模式' }).click()
  await expect(page.getByLabel('类名', { exact: true })).toHaveValue('Student')
  await page.getByRole('button', { name: '应用更改' }).click()
  await page.getByRole('button', { name: '源码模式' }).click()
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveValue(/class Student/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.setViewportSize({ width: 1280, height: 800 })
  await expect(splitter).toHaveAttribute('aria-valuenow', '52')
})
