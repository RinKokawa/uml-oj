import { expect, test } from '@playwright/test'

test('defaults to dark including the canvas; switching theme preserves editing and persists', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const root = page.locator('html')
  const editor = page.locator('.editor-host')
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await expect(root).toHaveAttribute('data-theme', 'dark')
  await expect(source).toHaveCSS('background-color', 'rgb(29, 32, 37)')
  await source.fill('@startuml\nclass Student\n@enduml')
  await page.getByRole('button', { name: '切换到可视化绘图' }).click()
  await expect(editor).toHaveAttribute('data-theme', 'dark')
  await expect(editor.locator('.react-flow__node')).toContainText('Student')
  expect((await editor.evaluate(el => getComputedStyle(el).getPropertyValue('--apollon-background'))).trim()).toBe('#1d2025')
  await page.getByRole('button', { name: '切换到亮色模式' }).click()
  await expect(root).toHaveAttribute('data-theme', 'light')
  await expect(editor).toHaveAttribute('data-theme', 'light')
  await expect(editor.locator('.react-flow__node')).toContainText('Student')
  expect((await editor.evaluate(el => getComputedStyle(el).getPropertyValue('--apollon-background'))).trim()).not.toBe('#1d2025')
  await page.getByRole('button', { name: 'PlantUML 源码模式' }).click()
  await expect(source).toHaveValue('@startuml\nclass Student\n@enduml')
  await expect(source).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await page.reload()
  await expect(root).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: '切换到暗色模式' }).click()
  await page.reload()
  await expect(root).toHaveAttribute('data-theme', 'dark')
})

test('theme toggle and dark layout work on narrow screens', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  await expect(page.getByRole('button', { name: '切换到亮色模式' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await page.getByRole('button', { name: '切换到亮色模式' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
})
