import { expect, test } from '@playwright/test'

test('section navigation stays in the header; problem and editor start together', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/')
  const header = page.locator('header')
  await expect(header.getByRole('navigation', { name: '练习分区' })).toBeVisible()
  await expect(page.locator('main .section-nav, .section-choices')).toHaveCount(0)
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const panel = page.locator('#problem-panel')
  const workspace = page.locator('#workspace')
  const problemBox = await panel.boundingBox()
  const editorBox = await workspace.boundingBox()
  expect(problemBox!.y).toBe(editorBox!.y)
  expect(problemBox!.y).toBeLessThan(100)
  await header.getByRole('button', { name: '正式挑战' }).click()
  await expect(page.getByRole('heading', { name: '正式题库', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '开始作答：项目管理系统' }).click()
  await expect(page.getByRole('heading', { name: '项目管理系统', exact: true })).toBeVisible()
  await expect(header.getByRole('button', { name: '正式挑战' })).toHaveAttribute('aria-current', 'page')
  await expect(page.locator('.lesson-card')).toHaveCount(0)
})

test('mode controls indicate the active view and keyboard submit reveals feedback', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const code = page.getByRole('button', { name: 'PlantUML 源码模式' })
  const canvas = page.getByRole('button', { name: '切换到可视化绘图' })
  await expect(code).toHaveAttribute('aria-pressed', 'true')
  await expect(canvas).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: '收起题面' }).click()
  await expect(page.getByLabel('题目说明')).toBeHidden()
  await page.getByRole('button', { name: '显示题面' }).click()
  await expect(page.getByLabel('题目说明')).toBeVisible()
  const textarea = page.getByRole('textbox', { name: 'PlantUML source' })
  await textarea.fill('@startuml\nclass Student\n@enduml')
  await textarea.press('Control+Enter')
  await expect(page.locator('.verdict')).toContainText('本关通过')
  await expect(page.locator('.feedback-anchor')).toBeInViewport()
  await canvas.click()
  await expect(canvas).toHaveAttribute('aria-pressed', 'true')
  await expect(code).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('.react-flow__node')).toContainText('Student')
  await code.click()
  await expect(textarea).toHaveValue('@startuml\nclass Student\n@enduml')
  await textarea.fill('@startuml\ninterface Student\n@enduml')
  await canvas.click()
  await expect(page.getByRole('alert')).toContainText('无法切换模式')
  await expect(code).toHaveAttribute('aria-pressed', 'true')
  await expect(textarea).toHaveValue('@startuml\ninterface Student\n@enduml')
})

test('mobile layout keeps the task first, jumps to editor and has no horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '开始学习：第 1 关：认识类' }).click()
  const task = page.getByRole('heading', { name: '本关任务' })
  const jump = page.getByRole('link', { name: '开始作答' })
  await expect(task).toBeVisible()
  await expect(jump).toBeVisible()
  await jump.click()
  await expect(page.getByRole('heading', { name: '开始建模' })).toBeInViewport()
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toBeInViewport()
  await page.getByRole('button', { name: '切换到可视化绘图' }).click()
  await expect(page.getByRole('button', { name: '显示工具箱' })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('.react-flow__node')).toContainText('Example')
  await page.getByRole('button', { name: '显示工具箱' }).click()
  await expect(page.getByRole('button', { name: '隐藏工具箱' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '隐藏工具箱' }).click()
  await expect(page.getByRole('button', { name: '显示工具箱' })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('link', { name: '返回题目和提示' }).click()
  await expect(page.getByRole('heading', { name: '第 1 关：认识类', exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.getByRole('button', { name: '知识讲解与操作步骤' }).click()
  await expect(page.getByRole('button', { name: '知识讲解与操作步骤' })).toHaveAttribute('aria-expanded', 'false')
})
